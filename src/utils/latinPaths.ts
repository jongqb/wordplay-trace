// Unified getter based on char and letterCase preference
export function getStrokesForChar(
  char: string,
  letterCase: 'uppercase' | 'lowercase' = 'uppercase'
): StrokeDefinition[] {
  if (letterCase === 'lowercase') {
    const lower = char.toLowerCase();
    if (LOWERCASE_LETTER_STROKES[lower]) {
      return LOWERCASE_LETTER_STROKES[lower];
    }
  }

  const upper = char.toUpperCase();
  if (UPPERCASE_LETTER_STROKES[upper]) {
    return UPPERCASE_LETTER_STROKES[upper];
  }

  if (LOWERCASE_LETTER_STROKES[char.toLowerCase()]) {
    return LOWERCASE_LETTER_STROKES[char.toLowerCase()];
  }

  // Fallback for punctuation or symbols
  return [
    {
      strokeIndex: 1,
      path: 'M 30 18 L 30 84',
      startPoint: [30, 18],
      endPoint: [30, 84],
      guidePoints: [[30, 18], [30, 40], [30, 62], [30, 84]],
      directionDescription: 'Stem down',
    },
    {
      strokeIndex: 2,
      path: 'M 30 50 L 70 50',
      startPoint: [30, 50],
      endPoint: [70, 50],
      guidePoints: [[30, 50], [43, 50], [57, 50], [70, 50]],
      directionDescription: 'Cross across',
    },
  ];
}
